-- ============================================================================
-- MIGRASI SKEMA: STABILITAS URUTAN SOAL (KOLOM urutan PADA TABEL soal_ujian)
-- ============================================================================

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'soal_ujian' AND column_name = 'urutan'
    ) THEN
        ALTER TABLE public.soal_ujian ADD COLUMN urutan BIGINT GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_soal_ujian_mapel_npsn_urutan
ON public.soal_ujian (id_mapel, npsn, urutan, id_soal);

NOTIFY pgrst, 'reload schema';
