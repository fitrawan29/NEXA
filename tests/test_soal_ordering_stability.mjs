#!/usr/bin/env node
/**
 * Regression Test: Question Ordering Stability on Edit + Per-Student Exam Shuffling
 */

import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { fetchAPI } from '../src/api.js';
import { supabaseClient } from '../src/config.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const apiCode = fs.readFileSync(path.resolve(projectRoot, 'src', 'api.js'), 'utf8');
const examRoomCode = fs.readFileSync(path.resolve(projectRoot, 'src', 'views', 'ExamRoom.jsx'), 'utf8');
const schemaCode = fs.readFileSync(path.resolve(projectRoot, 'database_backups', 'schema_master_init.sql'), 'utf8');
const migrationCode = fs.readFileSync(path.resolve(projectRoot, 'database_backups', 'migration_urutan_soal.sql'), 'utf8');

let passed = 0;
let failed = 0;

async function runCheck(name, fn) {
  try {
    await fn();
    passed++;
    console.log(`  [PASS] ${name}`);
  } catch (err) {
    failed++;
    console.error(`  [FAIL] ${name}: ${err.message}`);
  }
}

console.log('Running Question Ordering Stability Tests...');

await runCheck('Migration & schema define urutan BIGINT GENERATED BY DEFAULT AS IDENTITY', async () => {
  assert.ok(schemaCode.includes('urutan BIGINT GENERATED BY DEFAULT AS IDENTITY'));
  assert.ok(migrationCode.includes('urutan BIGINT GENERATED BY DEFAULT AS IDENTITY'));
  assert.ok(schemaCode.includes('idx_soal_ujian_mapel_npsn_urutan'));
});

await runCheck('get_soal_by_mapel, get_soal_ujian, and get_analisis_butir_soal enforce stable order with fallback', async () => {
  assert.ok(apiCode.includes('async function executeSoalOrderWithFallback'));

  const getMapelSlice = apiCode.slice(
    apiCode.indexOf("case 'get_soal_by_mapel':"),
    apiCode.indexOf("case 'create_soal_mapel':")
  );
  assert.ok(getMapelSlice.includes('executeSoalOrderWithFallback'));
  assert.ok(getMapelSlice.includes(".order('urutan', { ascending: true })"));
  assert.ok(getMapelSlice.includes(".order('id_soal', { ascending: true })"));

  const getUjianSlice = apiCode.slice(
    apiCode.indexOf("case 'get_soal_ujian':"),
    apiCode.indexOf("case 'catat_pelanggaran':")
  );
  assert.ok(getUjianSlice.includes('executeSoalOrderWithFallback'));
  assert.ok(getUjianSlice.includes(".order('urutan', { ascending: true })"));

  const getAnalisisSlice = apiCode.slice(
    apiCode.indexOf("case 'get_analisis_butir_soal':"),
    apiCode.indexOf('let q = supabaseClient.from(\'log_ujian\')')
  );
  assert.ok(getAnalisisSlice.includes('executeSoalOrderWithFallback'));
  assert.ok(getAnalisisSlice.includes(".order('urutan', { ascending: true })"));
});

await runCheck('update_soal_mapel does not mutate urutan column', async () => {
  const updateSlice = apiCode.slice(
    apiCode.indexOf("case 'update_soal_mapel':"),
    apiCode.indexOf("case 'delete_soal_mapel':")
  );
  assert.ok(!updateSlice.includes('updateData.urutan'));
});

await runCheck('ExamRoom.jsx preserves seededShuffle when jadwal.acak_soal is active', async () => {
  assert.ok(examRoomCode.includes('if (jadwal.acak_soal) {'));
  assert.ok(examRoomCode.includes('seededShuffle(parsedSoal, baseSeed)'));
});

await runCheck('Live DB roundtrip: order stays stable after editing text, image, and bobot', async () => {
  const { data: mapels, error: mapelErr } = await supabaseClient
    .from('mata_pelajaran')
    .select('id_mapel, npsn')
    .limit(1);

  if (mapelErr || !mapels || mapels.length === 0) {
    throw new Error('Tidak dapat mengambil sample mata_pelajaran untuk roundtrip DB: ' + (mapelErr?.message || 'kosong'));
  }

  const { id_mapel, npsn } = mapels[0];
  const suffix = Date.now().toString(36).toUpperCase();
  const ids = [
    `TEST-ORDER-${suffix}-1`,
    `TEST-ORDER-${suffix}-2`,
    `TEST-ORDER-${suffix}-3`
  ];

  try {
    for (let i = 0; i < ids.length; i++) {
      const createRes = await fetchAPI('create_soal_mapel', {
        id_soal: ids[i],
        id_mapel,
        npsn,
        tipe_soal: 'PG',
        pertanyaan: `Soal uji urutan #${i + 1}`,
        opsi: ['A', 'B', 'C', 'D', 'E'],
        kunci_jawaban: 'A',
        bobot: 10
      });
      assert.equal(createRes.status, 'success', createRes.message);
    }

    const beforeRes = await fetchAPI('get_soal_by_mapel', { id_mapel, npsn });
    assert.equal(beforeRes.status, 'success', beforeRes.message);
    const beforePositions = ids.map(id => beforeRes.data.findIndex(s => s.id_soal === id));
    assert.ok(beforePositions.every(pos => pos >= 0), 'Semua soal uji harus ditemukan');
    assert.ok(
      beforePositions[0] < beforePositions[1] && beforePositions[1] < beforePositions[2],
      `Urutan awal tidak sesuai: ${JSON.stringify(beforePositions)}`
    );

    // Edit question #1: text + image + bobot
    const updRes = await fetchAPI('update_soal_mapel', {
      id_soal: ids[0],
      id_mapel,
      npsn,
      pertanyaan: `Soal uji urutan #1 (DIEDIT)`,
      gambar: 'https://example.com/test-image.png',
      bobot: 25
    });
    assert.equal(updRes.status, 'success', updRes.message);

    const afterRes = await fetchAPI('get_soal_by_mapel', { id_mapel, npsn });
    assert.equal(afterRes.status, 'success', afterRes.message);
    const afterPositions = ids.map(id => afterRes.data.findIndex(s => s.id_soal === id));
    assert.deepEqual(
      afterPositions,
      beforePositions,
      `Urutan berubah setelah edit! Sebelum: ${beforePositions}, Sesudah: ${afterPositions}`
    );

    const editedRow = afterRes.data.find(s => s.id_soal === ids[0]);
    assert.equal(editedRow.bobot, 25);
    assert.equal(editedRow.gambar, 'https://example.com/test-image.png');
    assert.equal(editedRow.pertanyaan, 'Soal uji urutan #1 (DIEDIT)');
  } finally {
    await fetchAPI('delete_soal_bulk', { ids, npsn });
  }
});

console.log(`\nSummary: ${passed} passed, ${failed} failed.`);
if (failed > 0) process.exit(1);
